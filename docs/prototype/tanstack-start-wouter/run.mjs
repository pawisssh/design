// PROTOTYPE (#336), throwaway. Runs the forked reader (./react.mjs) and used.mjs's family walk on each sample,
// against the answer key in NOTES.md, and writes out/<sample>.json and out/report.md.
//   node docs/prototype/tanstack-start-wouter/run.mjs <lovable clone> <replit clone>/artifacts/hopebridge
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { walk } from '../../../skills/to-handoff/scripts/reader.mjs';
import { readReact } from './react.mjs';

const OUT = fileURLToPath(new URL('out/', import.meta.url));
const [lovable, replit] = process.argv.slice(2);
if (!replit) { console.error('usage: run.mjs <lovable> <replit>/artifacts/hopebridge'); process.exit(1); }

// The answer key (NOTES.md), written before the fork ran.
const KEY = {
  lovable: {
    screens: ['/', ...'ai-insights analytics assets catalog dashboard help inventory locations maintenance movements purchase-orders requests settings suppliers'.split(' ').map(p => `/app/${p}`)],
    families: null, // an upper bound only: the app code's imports, measured below
  },
  replit: {
    screens: ['/', '/about', '/projects', '/projects/:slug', '/volunteer', '/donate', '/events', '/blog', '/blog/:slug', '/gallery', '/contact'],
    families: ['Breadcrumbs', 'accordion', 'form', 'input', 'textarea'],
  },
};

const sorted = xs => [...xs].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));

// Every file under src/ outside the Code Library, and the Code Library files each imports (static imports only).
function appImports(root, uiDir) {
  const out = new Map();
  const visit = d => {
    for (const ent of readdirSync(join(root, d), { withFileTypes: true })) {
      const rel = posix.join(d, ent.name);
      if (ent.isDirectory()) { if (rel + '/' !== uiDir) visit(rel); continue; }
      if (!/\.(tsx?|jsx?)$/.test(ent.name)) continue;
      const text = readFileSync(join(root, rel), 'utf8');
      for (const m of text.matchAll(/^import\s+(type\s+)?[^;]*?from\s+['"]([^'"]+)['"]/gm)) {
        const spec = m[2];
        const name = spec.startsWith('@/components/ui/') ? spec.slice('@/components/ui/'.length) : /(^|\/)components\/ui\/([^/]+)$/.test(spec) || /^\.\.?\/(\.\.\/)*ui\/([^/]+)$/.test(spec) ? spec.split('/').pop() : null;
        if (!name) continue;
        if (!out.has(name)) out.set(name, []);
        out.get(name).push({ file: rel, typeOnly: Boolean(m[1]) });
      }
    }
  };
  visit('src');
  return out;
}

function measure(key, root) {
  const t0 = performance.now();
  const r = readReact(root);
  const ms = Math.round(performance.now() - t0);
  const perScreen = {};
  const used = new Set();
  for (const s of r.screens) {
    const fam = new Set();
    const visit = el => {
      const file = el.component && el.component.kind === 'ui' && el.component.file;
      if (file && posix.dirname(file) + '/' === r.uiDir) fam.add(posix.basename(file).replace(/\.[jt]sx?$/, ''));
    };
    for (const tree of [s.root, s.mount]) if (tree) walk(tree, visit);
    perScreen[s.route] = sorted(fam);
    fam.forEach(f => used.add(f));
  }
  const all = readdirSync(join(root, r.uiDir)).filter(f => f.endsWith('.tsx')).map(f => f.slice(0, -4));
  const imports = appImports(root, r.uiDir);
  const read = new Set(r.files);
  // A family the app code imports but no screen renders: its importers, and whether the reader read each one.
  const missed = sorted([...imports.keys()].filter(f => !used.has(f))).map(f => ({ family: f, importers: imports.get(f).map(i => ({ ...i, read: read.has(i.file) })) }));
  const screens = r.screens.map(s => s.route);
  const k = KEY[key];
  let crossCheck = null;
  if (r.router === 'tanstack-start') {
    // routeTree.gen.ts is generated by TanStack's plugin: a cross-check only, never the reader's source.
    const gen = readFileSync(join(root, 'src/routeTree.gen.ts'), 'utf8');
    const genFiles = sorted([...gen.matchAll(/from '\.\/routes\/([^']+)'/g)].map(m => m[1]));
    const readRoutes = sorted(r.files.filter(f => f.startsWith('src/routes/')).map(f => f.slice('src/routes/'.length).replace(/\.[jt]sx?$/, '')));
    crossCheck = { genFiles, readRoutes, same: JSON.stringify(genFiles) === JSON.stringify(readRoutes) };
  }
  return {
    sample: key, kind: r.kind, router: r.router, title: r.title, ms, files: r.files.length, rules: r.rules.length, tailwind: r.tailwind, uiDir: r.uiDir,
    screens, screensKey: k.screens,
    screensMissing: k.screens.filter(x => !screens.includes(x)), screensExtra: screens.filter(x => !k.screens.includes(x)),
    ignored: r.ignored, perScreen, used: sorted(used), all: all.length,
    familiesKey: k.families || sorted(imports.keys()),
    familiesKeyIsUpperBound: !k.families,
    familiesMissing: (k.families || sorted(imports.keys())).filter(f => !used.has(f)),
    familiesExtra: k.families ? sorted(used).filter(f => !k.families.includes(f)) : [],
    missed, crossCheck,
  };
}

mkdirSync(OUT, { recursive: true });
const results = [measure('lovable', lovable), measure('replit', replit)];
for (const m of results) writeFileSync(join(OUT, `${m.sample}.json`), `${JSON.stringify(m, null, 2)}\n`);

const lines = ['# #336 prototype: measured', '', `Generated by \`run.mjs\` from the forked reader. The samples' paths are left out.`, ''];
for (const m of results) {
  lines.push(`## ${m.sample} (${m.router || 'vite + index.html'}${m.router ? '' : ', wouter'})`, '');
  lines.push(`- Title: ${m.title}. Files read: ${m.files}. CSS rules: ${m.rules}. Tailwind: ${m.tailwind}. Code Library: \`${m.uiDir}\`. Read in ${m.ms} ms.`);
  lines.push(`- Screens: ${m.screens.length} found, ${m.screensKey.length} in the answer key. Missing: ${m.screensMissing.join(', ') || 'none'}. Extra: ${m.screensExtra.join(', ') || 'none'}.`);
  lines.push(`- Ignored: ${m.ignored.length ? m.ignored.map(i => `\`${i}\``).join('; ') : 'nothing'}.`);
  if (m.crossCheck) lines.push(`- routeTree.gen.ts cross-check: ${m.crossCheck.same ? 'the same route files' : `differs: generated ${m.crossCheck.genFiles.join(', ')}; read ${m.crossCheck.readRoutes.join(', ')}`}.`);
  lines.push(`- used.mjs default list: **${m.used.length}** families: ${m.used.join(', ')}. \`--all\`: ${m.all}.`);
  lines.push(`- Answer key${m.familiesKeyIsUpperBound ? ' (upper bound: every Code Library import in app code)' : ''}: ${m.familiesKey.length}. Missing: ${m.familiesMissing.join(', ') || 'none'}. Extra: ${m.familiesExtra.join(', ') || 'none'}.`);
  if (m.missed.length) {
    lines.push('', '| Imported by app code, rendered by no screen | Importers (read by the reader?) |', '|---|---|');
    for (const x of m.missed) lines.push(`| ${x.family} | ${x.importers.map(i => `\`${i.file}\`${i.typeOnly ? ' (type only)' : ''} ${i.read ? 'read' : '**not read**'}`).join('; ')} |`);
  }
  lines.push('', '| Screen | Families |', '|---|---|');
  for (const [route, fam] of Object.entries(m.perScreen)) lines.push(`| \`${route}\` | ${fam.join(', ') || '(none)'} |`);
  lines.push('');
}
writeFileSync(join(OUT, 'report.md'), lines.join('\n'));
console.log(lines.join('\n'));
console.error(`wrote ${results.map(m => `out/${m.sample}.json`).join(', ')} and out/report.md (${basename(OUT)})`);
